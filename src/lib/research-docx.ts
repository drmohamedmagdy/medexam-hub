import {
  AlignmentType,
  Document,
  HeadingLevel,
  ImageRun,
  Packer,
  PageBreak,
  Paragraph,
  Table,
  TableCell,
  TableRow,
  TextRun,
  WidthType,
} from "docx";
import { renderPrismaTextSummary, safeParsePrismaFlow } from "@/lib/prisma-flow";
import { svgToPng } from "@/lib/stats-charts";
import { fmt, fmtP } from "@/lib/stats-engine";
import type {
  CorrelationCell,
  DescriptiveRow,
  GroupMeansRow,
  HistogramBins,
  TTestResult,
} from "@/lib/stats-engine";

export type AnalysisExport = {
  id: string;
  kind: string;
  title: string;
  resultJson: string | null;
  resultSvg: string | null;
};

export type ResearchExport = {
  title: string;
  kindLabel: string;
  authorName: string | null;
  university: string | null;
  specialty: string | null;
  studyType: string | null;
  language: string;
  citationStyle: string;
  sections: Array<{ title: string; content: string; metadataJson?: string | null }>;
  analyses?: AnalysisExport[];
};

/**
 * Render a research project to a Word .docx Buffer. Plain-prose paragraphs,
 * with simple bullet detection so lines starting with "- ", "* ", "• " or
 * "1.", "2.", … become list items. The cover page has the title, the user's
 * name, university, and a generated-by stamp.
 */
export async function renderResearchDocx(p: ResearchExport): Promise<Buffer> {
  const cover: Paragraph[] = [
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { before: 1800, after: 400 },
      children: [
        new TextRun({
          text: p.kindLabel.toUpperCase(),
          bold: true,
          size: 22,
          color: "555555",
        }),
      ],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { before: 200, after: 600 },
      children: [
        new TextRun({ text: p.title, bold: true, size: 44 }),
      ],
    }),
    p.authorName
      ? new Paragraph({
          alignment: AlignmentType.CENTER,
          spacing: { before: 400, after: 200 },
          children: [new TextRun({ text: p.authorName, size: 26 })],
        })
      : new Paragraph({}),
    p.university
      ? new Paragraph({
          alignment: AlignmentType.CENTER,
          spacing: { after: 100 },
          children: [new TextRun({ text: p.university, italics: true, size: 22 })],
        })
      : new Paragraph({}),
    p.specialty || p.studyType
      ? new Paragraph({
          alignment: AlignmentType.CENTER,
          spacing: { after: 100 },
          children: [
            new TextRun({
              text: [p.specialty, p.studyType].filter(Boolean).join(" · "),
              size: 22,
              color: "666666",
            }),
          ],
        })
      : new Paragraph({}),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { before: 1200, after: 600 },
      children: [
        new TextRun({
          text: `Generated by MedExam Hub — Research Assistant · ${new Date().toLocaleDateString()}`,
          italics: true,
          size: 18,
          color: "888888",
        }),
      ],
    }),
    new Paragraph({ children: [new PageBreak()] }),
  ];

  const body: Paragraph[] = [];
  for (const section of p.sections) {
    body.push(
      new Paragraph({
        heading: HeadingLevel.HEADING_1,
        spacing: { before: 400, after: 200 },
        children: [new TextRun({ text: section.title, bold: true, size: 32 })],
      })
    );

    // PRISMA flow + any future diagram sections: render the structured
    // summary as text. Embedding SVG-rendered images directly is in
    // scope for Phase 3 — for V2 the user will see a clean numbered
    // list they can paste a screenshot next to.
    const prismaData = section.metadataJson
      ? safeParsePrismaFlow(section.metadataJson)
      : null;
    const effectiveText = prismaData
      ? renderPrismaTextSummary(prismaData) +
        "\n\n[A visual PRISMA flow diagram is shown in the on-screen editor — paste a screenshot here.]"
      : section.content;

    for (const line of effectiveText.split(/\r?\n/)) {
      const trimmed = line.trim();
      if (trimmed.length === 0) {
        body.push(new Paragraph({}));
        continue;
      }
      const bulletMatch = /^[-•*]\s+(.*)/.exec(trimmed);
      const numberedMatch = /^\d+[.)]\s+(.*)/.exec(trimmed);
      if (bulletMatch) {
        body.push(
          new Paragraph({
            bullet: { level: 0 },
            spacing: { after: 100 },
            children: [new TextRun({ text: bulletMatch[1], size: 22 })],
          })
        );
        continue;
      }
      if (numberedMatch) {
        body.push(
          new Paragraph({
            numbering: { reference: "default-numbered", level: 0 },
            spacing: { after: 100 },
            children: [new TextRun({ text: numberedMatch[1], size: 22 })],
          })
        );
        continue;
      }
      // Sub-heading detection: a short line ending with ":" gets bolded.
      if (trimmed.length < 80 && trimmed.endsWith(":")) {
        body.push(
          new Paragraph({
            spacing: { before: 200, after: 100 },
            children: [
              new TextRun({ text: trimmed.replace(/:$/, ""), bold: true, size: 24 }),
            ],
          })
        );
        continue;
      }
      body.push(
        new Paragraph({
          spacing: { after: 140 },
          children: [new TextRun({ text: trimmed, size: 22 })],
        })
      );
    }
  }

  // Append a Statistical Analysis appendix with computed numbers and PNG
  // charts so the Word file is self-contained — no need to paste anything
  // in manually.
  const analysisChildren: (Paragraph | Table)[] = [];
  const populated = (p.analyses ?? []).filter((a) => a.resultJson);
  if (populated.length > 0) {
    analysisChildren.push(
      new Paragraph({
        heading: HeadingLevel.HEADING_1,
        spacing: { before: 600, after: 200 },
        children: [
          new TextRun({ text: "Statistical Analysis Appendix", bold: true, size: 32 }),
        ],
      })
    );
    for (const a of populated) {
      analysisChildren.push(
        new Paragraph({
          heading: HeadingLevel.HEADING_2,
          spacing: { before: 320, after: 140 },
          children: [new TextRun({ text: a.title, bold: true, size: 26 })],
        })
      );
      const blocks = await analysisBlocksForDocx(a);
      for (const b of blocks) analysisChildren.push(b);
    }
  }

  const doc = new Document({
    creator: p.authorName ?? "MedExam Hub",
    title: p.title,
    description: p.kindLabel,
    numbering: {
      config: [
        {
          reference: "default-numbered",
          levels: [
            {
              level: 0,
              format: "decimal",
              text: "%1.",
              alignment: AlignmentType.LEFT,
            },
          ],
        },
      ],
    },
    sections: [
      {
        properties: {},
        children: [...cover, ...body, ...analysisChildren],
      },
    ],
  });

  return Buffer.from(await Packer.toBuffer(doc));
}

// ─────────────────────────────────────────────────────────────────────────────
// Analysis → DOCX block(s). Each kind produces either a styled table, a
// rasterised PNG of the SVG chart, or both.
// ─────────────────────────────────────────────────────────────────────────────

async function analysisBlocksForDocx(a: AnalysisExport): Promise<(Paragraph | Table)[]> {
  const out: (Paragraph | Table)[] = [];
  let parsed: unknown = null;
  try {
    parsed = a.resultJson ? JSON.parse(a.resultJson) : null;
  } catch {
    parsed = null;
  }
  if (!parsed) {
    out.push(textPara("(No computed result.)"));
    return out;
  }

  if (a.kind === "descriptives") {
    out.push(descriptivesTable(parsed as DescriptiveRow[]));
  } else if (a.kind === "compare_means") {
    const r = parsed as { tTest: TTestResult; groupMeans: GroupMeansRow[] };
    out.push(groupMeansTable(r.groupMeans));
    out.push(...tTestBlock(r.tTest));
    if (a.resultSvg) {
      const png = await rasteriseChart(a.resultSvg);
      if (png) out.push(imageParagraph(png));
    }
  } else if (a.kind === "correlation") {
    out.push(correlationTable(parsed as { columns: string[]; cells: CorrelationCell[] }));
  } else if (a.kind === "histogram") {
    const h = parsed as HistogramBins;
    out.push(
      textPara(
        `n = ${h.n} · mean = ${fmt(h.mean)} · range [${fmt(h.min)}, ${fmt(h.max)}]`
      )
    );
    if (a.resultSvg) {
      const png = await rasteriseChart(a.resultSvg);
      if (png) out.push(imageParagraph(png));
    }
  }
  return out;
}

async function rasteriseChart(svg: string): Promise<Buffer | null> {
  try {
    return await svgToPng(svg, 900);
  } catch {
    return null;
  }
}

function imageParagraph(png: Buffer): Paragraph {
  return new Paragraph({
    spacing: { before: 160, after: 200 },
    children: [
      new ImageRun({
        // docx requires "type" plus dimensions for raster images.
        type: "png",
        data: new Uint8Array(png),
        transformation: { width: 540, height: 300 },
      }),
    ],
  });
}

function textPara(text: string, opts?: { bold?: boolean }): Paragraph {
  return new Paragraph({
    spacing: { after: 140 },
    children: [new TextRun({ text, size: 22, bold: opts?.bold })],
  });
}

function headerCell(text: string): TableCell {
  return new TableCell({
    children: [
      new Paragraph({
        children: [new TextRun({ text, bold: true, size: 20 })],
      }),
    ],
  });
}

function bodyCell(text: string, opts?: { mono?: boolean }): TableCell {
  return new TableCell({
    children: [
      new Paragraph({
        children: [
          new TextRun({
            text,
            size: 20,
            font: opts?.mono ? "Courier New" : undefined,
          }),
        ],
      }),
    ],
  });
}

function descriptivesTable(rows: DescriptiveRow[]): Table {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: [
      new TableRow({
        children: ["Variable", "n", "Mean", "Median", "SD", "Min", "Max", "Q1", "Q3"].map(
          headerCell
        ),
      }),
      ...rows.map(
        (r) =>
          new TableRow({
            children: [
              bodyCell(r.column),
              bodyCell(String(r.n), { mono: true }),
              bodyCell(fmt(r.mean), { mono: true }),
              bodyCell(fmt(r.median), { mono: true }),
              bodyCell(fmt(r.sd), { mono: true }),
              bodyCell(fmt(r.min), { mono: true }),
              bodyCell(fmt(r.max), { mono: true }),
              bodyCell(fmt(r.q1), { mono: true }),
              bodyCell(fmt(r.q3), { mono: true }),
            ],
          })
      ),
    ],
  });
}

function groupMeansTable(rows: GroupMeansRow[]): Table {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: [
      new TableRow({
        children: ["Group", "n", "Mean", "SD"].map(headerCell),
      }),
      ...rows.map(
        (r) =>
          new TableRow({
            children: [
              bodyCell(r.group),
              bodyCell(String(r.n), { mono: true }),
              bodyCell(fmt(r.mean), { mono: true }),
              bodyCell(fmt(r.sd), { mono: true }),
            ],
          })
      ),
    ],
  });
}

function tTestBlock(t: TTestResult): Paragraph[] {
  return [
    textPara(
      `Welch's t-test: t = ${fmt(t.t, 3)}, df = ${fmt(t.df, 1)}, mean diff = ${fmt(
        t.meanDifference
      )}, p = ${fmtP(t.pValue)}`,
      { bold: true }
    ),
  ];
}

function correlationTable(matrix: { columns: string[]; cells: CorrelationCell[] }): Table {
  const lookup = (rowCol: string, colCol: string) =>
    matrix.cells.find((c) => c.rowColumn === rowCol && c.colColumn === colCol);
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: [
      new TableRow({
        children: ["", ...matrix.columns].map(headerCell),
      }),
      ...matrix.columns.map(
        (rowCol) =>
          new TableRow({
            children: [
              bodyCell(rowCol),
              ...matrix.columns.map((colCol) => {
                const c = lookup(rowCol, colCol);
                return bodyCell(rowCol === colCol ? "—" : c ? fmt(c.r, 2) : "—", {
                  mono: true,
                });
              }),
            ],
          })
      ),
    ],
  });
}
